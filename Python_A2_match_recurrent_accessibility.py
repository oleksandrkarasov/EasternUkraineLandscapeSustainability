#!/usr/bin/env python3
"""
Create the recurrent-visitation accessibility-matched background layer.

This script is deliberately separate from the primary effort-weighted draw.
The primary layer estimates realised visitation propensity, whereas this layer
conditions the negative class on a similar observation/accessibility process.

The candidate pool was generated by the primary script's effort-weighted draw,
not by uniform sampling of every eligible cell. Consequently, the matched
background inherits that pool's broad spatial support. The SMD gate controls
the prespecified accessibility marginals (log effort and log distance to
infrastructure), but does not claim balance on every spatial characteristic.

Matching rules
--------------
1. Both classes use the recurrent core green/blue WorldCover domain:
   10, 20, 30, 80, 90 and 100. Cropland, bare/sparse and built-up are absent.
2. Pseudo-absence candidates must have non-zero target-group effort.
3. Matching is exact on the pre-2022 ORDLO indicator.
4. Within each ORDLO stratum, candidates are matched one-to-one without
   replacement on robustly standardised log effort and log distance to
   infrastructure.
5. Hard-to-match presences are allocated first; all random tie-breaking is
   controlled by SEED.
6. Presences outside adequate common support may be removed using a
   predeclared coarsened-exact-matching search. The same retained presence set
   and its paired pseudo-absences are both exported.
7. The script fails if |standardised mean difference| exceeds 0.10 or if less
   than 70% of recurrent presences remain, rather than silently exporting an
   unbalanced or narrowly selected sensitivity set.

The output includes a GeoPackage for archiving, a zipped Shapefile for direct
Google Earth Engine upload, a field crosswalk, and balance diagnostics.
"""

