def robust_transform(
    presence: pd.DataFrame, candidates: pd.DataFrame
) -> tuple[np.ndarray, np.ndarray, dict[str, float]]:
    """Return comparable two-dimensional matching coordinates.

    log_effort is already transformed. Distance is log1p-transformed because
    the raw distance distribution has a long right tail. Centre and scale are
    calculated from the combined stratum with an IQR scale, making the result
    insensitive to a few extreme candidate locations.
    """
    p = np.column_stack([
        presence["log_effort"].to_numpy(float),
        np.log1p(presence["dist_infra_m"].to_numpy(float)),
    ])
    c = np.column_stack([
        candidates["log_effort"].to_numpy(float),
        np.log1p(candidates["dist_infra_m"].to_numpy(float)),
    ])
    combined = np.vstack([p, c])
    centre = np.nanmedian(combined, axis=0)
    q25, q75 = np.nanpercentile(combined, [25, 75], axis=0)
    scale = q75 - q25
    scale[~np.isfinite(scale) | (scale < 1e-9)] = 1.0
    return (
        (p - centre) / scale,
        (c - centre) / scale,
        {
            "centre_log_effort": float(centre[0]),
            "centre_log_distance": float(centre[1]),
            "scale_log_effort_iqr": float(scale[0]),
            "scale_log_distance_iqr": float(scale[1]),
        },
    )


def greedy_without_replacement(
    presence_xy: np.ndarray,
    candidate_xy: np.ndarray,
    rng: np.random.Generator,
) -> tuple[np.ndarray, np.ndarray]:
    if len(candidate_xy) < len(presence_xy):
        raise ValueError(
            f"Only {len(candidate_xy)} candidates for {len(presence_xy)} presences")

    tree = cKDTree(candidate_xy)
    k = min(NEIGHBOURS_TO_QUERY, len(candidate_xy))
    distances, indices = tree.query(presence_xy, k=k)
    if k == 1:
        distances = distances[:, None]
        indices = indices[:, None]

    # Allocate the most isolated presences first. A seeded jitter resolves exact
    # ties without making the result machine/order dependent.
    difficulty = distances[:, 0] + rng.uniform(0.0, 1e-12, len(presence_xy))
    order = np.argsort(difficulty)[::-1]
    used = np.zeros(len(candidate_xy), dtype=bool)
    selected = np.full(len(presence_xy), -1, dtype=int)
    selected_distance = np.full(len(presence_xy), np.nan, dtype=float)

    for presence_index in order:
        available_rank = np.flatnonzero(~used[indices[presence_index]])
        if available_rank.size:
            rank = int(available_rank[0])
            candidate_index = int(indices[presence_index, rank])
            distance = float(distances[presence_index, rank])
        else:
            unused = np.flatnonzero(~used)
            if unused.size == 0:
                raise RuntimeError("Candidate pool exhausted during matching")
            delta = candidate_xy[unused] - presence_xy[presence_index]
            local_rank = int(np.argmin(np.einsum("ij,ij->i", delta, delta)))
            candidate_index = int(unused[local_rank])
            distance = float(np.linalg.norm(delta[local_rank]))
        used[candidate_index] = True
        selected[presence_index] = candidate_index
        selected_distance[presence_index] = distance

    if np.any(selected < 0) or len(np.unique(selected)) != len(selected):
        raise RuntimeError("Matching did not produce a unique candidate per presence")
    return selected, selected_distance


def standardised_mean_difference(a: np.ndarray, b: np.ndarray) -> float:
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    pooled = np.sqrt((np.nanvar(a, ddof=1) + np.nanvar(b, ddof=1)) / 2.0)
    if not np.isfinite(pooled) or pooled < 1e-12:
        return 0.0 if np.isclose(np.nanmean(a), np.nanmean(b)) else np.inf
    return float((np.nanmean(a) - np.nanmean(b)) / pooled)


def diagnostic_rows(
    presence: pd.DataFrame,
    background: pd.DataFrame,
    stage: str,
) -> list[dict[str, float | int | str]]:
    rows: list[dict[str, float | int | str]] = []
    subsets: list[tuple[str, pd.DataFrame, pd.DataFrame]] = [
        ("all", presence, background)]
    common_strata = sorted(
        set(presence["in_ordlo"].unique())
        & set(background["in_ordlo"].unique()))
    subsets.extend([
        (
            str(stratum),
            presence[presence["in_ordlo"] == stratum],
            background[background["in_ordlo"] == stratum],
        )
        for stratum in common_strata
    ])
    for stratum_label, p_frame, b_frame in subsets:
        variables = {
            "log_effort": (
                p_frame["log_effort"].to_numpy(float),
                b_frame["log_effort"].to_numpy(float)),
            "log1p_dist_infra_m": (
                np.log1p(p_frame["dist_infra_m"].to_numpy(float)),
                np.log1p(b_frame["dist_infra_m"].to_numpy(float))),
            "dist_infra_m_raw_diagnostic": (
                p_frame["dist_infra_m"].to_numpy(float),
                b_frame["dist_infra_m"].to_numpy(float)),
        }
        for column, (p, b) in variables.items():
            if len(p) < 2 or len(b) < 2:
                continue
            ks = ks_2samp(p, b, alternative="two-sided", mode="auto")
            rows.append({
                "stage": stage,
                "stratum": stratum_label,
                "variable": column,
                "n_presence": len(p),
                "n_background": len(b),
                "presence_mean": float(np.mean(p)),
                "background_mean": float(np.mean(b)),
                "presence_sd": float(np.std(p, ddof=1)),
                "background_sd": float(np.std(b, ddof=1)),
                "smd_presence_minus_background":
                    standardised_mean_difference(p, b),
                "ks_statistic": float(ks.statistic),
                "ks_p_value": float(ks.pvalue),
            })
    return rows


def _quantile_edges(values: np.ndarray, number_of_bins: int) -> np.ndarray:
    """Return stable pooled quantile edges for coarsened exact matching."""
    probabilities = np.linspace(0.0, 1.0, number_of_bins + 1)
    edges = np.unique(np.quantile(values, probabilities))
    if len(edges) < 2:
        centre = float(values[0]) if len(values) else 0.0
        edges = np.array([centre - 0.5, centre + 0.5], dtype=float)
    return edges


def _bin_values(values: np.ndarray, edges: np.ndarray) -> np.ndarray:
    # Interior boundaries are sufficient; values at the upper endpoint remain
    # in the final bin. All inputs were checked as finite before matching.
    return np.searchsorted(edges[1:-1], values, side="right").astype(int)


def coarsened_exact_match_stratum(
    presence: gpd.GeoDataFrame,
    candidates: gpd.GeoDataFrame,
    number_of_bins: int,
    seed: int,
) -> tuple[gpd.GeoDataFrame, gpd.GeoDataFrame, dict[str, float]]:
    """Match within two-dimensional pooled-quantile cells.

    Exact matching on ORDLO is performed by the caller. Within a stratum,
    pooled quantile bins enforce common support in log effort and log distance.
    Where a bin contains fewer candidates than presences, a seeded subset of
    presences is retained. Nearest-neighbour allocation within each bin is
    without replacement.
    """
    p_xy, c_xy, scaling = robust_transform(presence, candidates)
    combined = np.vstack([p_xy, c_xy])
    effort_edges = _quantile_edges(combined[:, 0], number_of_bins)
    distance_edges = _quantile_edges(combined[:, 1], number_of_bins)
    p_bins = np.column_stack([
        _bin_values(p_xy[:, 0], effort_edges),
        _bin_values(p_xy[:, 1], distance_edges),
    ])
    c_bins = np.column_stack([
        _bin_values(c_xy[:, 0], effort_edges),
        _bin_values(c_xy[:, 1], distance_edges),
    ])

    rng = np.random.default_rng(seed)
    selected_presence: list[int] = []
    selected_candidate: list[int] = []
    selected_distance: list[float] = []
    keys = sorted(set(map(tuple, p_bins.tolist())))
    for key in keys:
        p_local = np.flatnonzero(np.all(p_bins == key, axis=1))
        c_local = np.flatnonzero(np.all(c_bins == key, axis=1))
        if len(c_local) == 0:
            continue
        number_to_match = min(len(p_local), len(c_local))
        if len(p_local) > number_to_match:
            p_local = np.sort(rng.choice(
                p_local, size=number_to_match, replace=False))
        # All candidates in this coarsened cell remain available to the
        # nearest-neighbour allocation; the helper guarantees uniqueness.
        candidate_rank, distances = greedy_without_replacement(
            p_xy[p_local], c_xy[c_local], rng)
        selected_presence.extend(p_local.tolist())
        selected_candidate.extend(c_local[candidate_rank].tolist())
        selected_distance.extend(distances.tolist())

    if not selected_presence:
        raise RuntimeError(
            f"No common-support pairs for ORDLO stratum using "
            f"{number_of_bins} bins")
    selected_presence_array = np.asarray(selected_presence, dtype=int)
    selected_candidate_array = np.asarray(selected_candidate, dtype=int)
    if len(np.unique(selected_candidate_array)) != len(selected_candidate_array):
        raise RuntimeError("A candidate was used more than once across CEM cells")

    p_out = presence.iloc[selected_presence_array].copy()
    b_out = candidates.iloc[selected_candidate_array].copy()
    b_out["match_distance"] = np.asarray(selected_distance, dtype=float)
    b_out["matched_presence_row"] = p_out.index.to_numpy()
    scaling["number_of_bins"] = int(number_of_bins)
    scaling["n_presence_before"] = int(len(presence))
    scaling["n_presence_retained"] = int(len(p_out))
    return p_out, b_out, scaling


def safe_field_map(columns: list[str]) -> dict[str, str]:
    mapping: dict[str, str] = {}
    used: set[str] = set()
    for column in columns:
        if column == "geometry":
            continue
        preferred = SHORT_FIELDS.get(column, column)
        base = re.sub(r"[^A-Za-z0-9_]", "_", str(preferred))[:10] or "field"
        candidate = base
        suffix = 1
        while candidate.lower() in used:
            suffix_text = str(suffix)
            candidate = base[: 10 - len(suffix_text)] + suffix_text
            suffix += 1
        mapping[column] = candidate
        used.add(candidate.lower())
    return mapping


def write_gee_zip(
    frame: gpd.GeoDataFrame,
    output_dir: Path,
    basename: str,
) -> tuple[Path, Path]:
    asset_name = ASSET_PREFIX + basename
    shp_dir = output_dir / "gee_shapefiles"
    shp_dir.mkdir(parents=True, exist_ok=True)
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    shp_path = shp_dir / f"{asset_name}.shp"
    zip_path = UPLOAD_DIR / f"{asset_name}.zip"
    crosswalk_path = output_dir / f"{basename}_fields.csv"
    field_map = safe_field_map(list(frame.columns))
    exported = frame.rename(columns=field_map)
    exported.to_file(shp_path, driver="ESRI Shapefile", encoding="UTF-8")
    pd.DataFrame([
        {"source_field": source, "gee_field": target}
        for source, target in field_map.items()
    ]).to_csv(crosswalk_path, index=False)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for extension in [".shp", ".shx", ".dbf", ".prj", ".cpg"]:
            sidecar = shp_path.with_suffix(extension)
            if sidecar.exists():
                archive.write(sidecar, arcname=sidecar.name)
    return zip_path, crosswalk_path


def main() -> None:
    args = parse_args()
    work_dir = args.work_dir.expanduser().resolve()
    presence_path = newest_match(
        work_dir,
        ["presences_recurrent_core_nondvi_matched_*_4326.gpkg",
         "presences_recurrent_core_nondvi_matched*.gpkg"],
        "Matched recurrent core green/blue presence layer",
    )
    pool_path = newest_match(
        work_dir,
        ["pa_pool_*_3857.gpkg", "pa_pool*.gpkg"],
        "Pseudo-absence candidate pool",
    )

    presences = canonicalise_columns(gpd.read_file(presence_path))
    candidates = canonicalise_columns(gpd.read_file(pool_path))
    if presences.crs is None or candidates.crs is None:
        raise ValueError("Both input layers must have a declared CRS")
    if presences.crs != candidates.crs:
        presences = presences.to_crs(candidates.crs)
    require_columns(
        presences,
        ["esa", "log_effort", "dist_infra_m", "in_ordlo",
         "n_user_days", "n_users", "n_dates", "span_days"],
        "Presence layer",
    )
    require_columns(
        candidates,
        ["esa", "effort_5km", "log_effort", "dist_infra_m", "in_ordlo"],
        "Candidate pool",
    )

    presences = presences[
        presences["esa"].isin(ANALYSIS_ESA_CLASSES)
    ].copy().reset_index(drop=True)
    recurrence_ok = (
        (pd.to_numeric(presences["n_user_days"], errors="coerce") >= 3) &
        (pd.to_numeric(presences["n_users"], errors="coerce") >= 2) &
        (pd.to_numeric(presences["n_dates"], errors="coerce") >= 2) &
        (pd.to_numeric(presences["span_days"], errors="coerce") >= 30)
    )
    if not bool(recurrence_ok.all()):
        raise ValueError(
            "The selected presence file contains cells that do not satisfy "
            "the predeclared recurrent rule. No background was exported.")
    candidates = candidates[
        candidates["esa"].isin(ANALYSIS_ESA_CLASSES)
        & (pd.to_numeric(candidates["effort_5km"], errors="coerce") > 0)
    ].copy().reset_index(drop=True)
    for frame in [presences, candidates]:
        frame["in_ordlo"] = pd.to_numeric(
            frame["in_ordlo"], errors="coerce").fillna(0).astype(int)
        for column in ["log_effort", "dist_infra_m"]:
            frame[column] = pd.to_numeric(frame[column], errors="coerce")
    presences = presences.dropna(
        subset=["log_effort", "dist_infra_m", "geometry"]).reset_index(drop=True)
    candidates = candidates.dropna(
        subset=["log_effort", "dist_infra_m", "geometry"]).reset_index(drop=True)
    presences = presences.loc[
        np.isfinite(presences["log_effort"])
        & np.isfinite(presences["dist_infra_m"])
        & (presences["dist_infra_m"] >= 0)
    ].reset_index(drop=True)
    candidates = candidates.loc[
        np.isfinite(candidates["log_effort"])
        & np.isfinite(candidates["dist_infra_m"])
        & (candidates["dist_infra_m"] >= 0)
    ].reset_index(drop=True)

    print(f"Eligible presences: {len(presences):,}")
    print(f"Eligible candidate pseudo-absences: {len(candidates):,}")
    candidate_diagnostics = diagnostic_rows(
        presences, candidates, "candidate_pool")
    attempts: list[dict[str, float | int | bool]] = []
    designs: list[dict[str, object]] = []

    for number_of_bins in CEM_BIN_OPTIONS:
        presence_parts: list[gpd.GeoDataFrame] = []
        background_parts: list[gpd.GeoDataFrame] = []
        transform_metadata: dict[str, dict[str, float]] = {}
        for stratum in sorted(presences["in_ordlo"].unique()):
            p = presences[presences["in_ordlo"] == stratum].copy()
            c = candidates[candidates["in_ordlo"] == stratum].copy()
            if c.empty:
                raise ValueError(
                    f"ORDLO stratum {stratum} has no eligible candidates")
            selected_p, selected_b, scaling = coarsened_exact_match_stratum(
                p, c, number_of_bins,
                seed=SEED + number_of_bins * 100 + int(stratum),
            )
            presence_parts.append(selected_p)
            background_parts.append(selected_b)
            transform_metadata[str(stratum)] = scaling

        selected_presences = gpd.GeoDataFrame(
            pd.concat(presence_parts, ignore_index=False),
            geometry="geometry", crs=presences.crs,
        )
        matched = gpd.GeoDataFrame(
            pd.concat(background_parts, ignore_index=True),
            geometry="geometry", crs=candidates.crs,
        )
        if len(selected_presences) != len(matched):
            raise RuntimeError("Matched presence/background counts differ")
        design_diagnostics = diagnostic_rows(
            selected_presences, matched, f"cem_{number_of_bins}_bins")
        design_frame = pd.DataFrame(design_diagnostics)
        gate_rows = design_frame[
            design_frame["variable"].isin(
                ["log_effort", "log1p_dist_infra_m"])
        ]
        worst_smd = float(
            gate_rows["smd_presence_minus_background"].abs().max())
        retention = float(len(selected_presences) / len(presences))
        passed = bool(
            np.isfinite(worst_smd)
            and worst_smd <= MAX_ABS_SMD
            and retention >= MIN_PRESENCE_RETENTION)
        attempts.append({
            "cem_bins_per_covariate": number_of_bins,
            "n_presence_input": int(len(presences)),
            "n_presence_retained": int(len(selected_presences)),
            "presence_retention_fraction": retention,
            "maximum_absolute_smd_all_and_strata": worst_smd,
            "smd_limit": MAX_ABS_SMD,
            "minimum_retention_required": MIN_PRESENCE_RETENTION,
            "passed_both_gates": passed,
        })
        designs.append({
            "bins": number_of_bins,
            "presences": selected_presences,
            "background": matched,
            "diagnostics": design_diagnostics,
            "scaling": transform_metadata,
            "worst_smd": worst_smd,
            "retention": retention,
            "passed": passed,
        })
        print(
            f"CEM {number_of_bins}x{number_of_bins}: retained "
            f"{len(selected_presences):,}/{len(presences):,} "
            f"({retention:.1%}); max |SMD|={worst_smd:.3f}; "
            f"passed={passed}")

    attempts_df = pd.DataFrame(attempts)
    attempts_path = work_dir / OUTPUT_ATTEMPTS
    attempts_df.to_csv(attempts_path, index=False)
    valid_designs = [design for design in designs if bool(design["passed"])]
    if valid_designs:
        # Maximise retained spatial units; use lower imbalance as a tie-break.
        selected_design = max(
            valid_designs,
            key=lambda design: (
                len(design["presences"]), -float(design["worst_smd"])),
        )
    else:
        # Write the most informative failed diagnostics before stopping.
        selected_design = min(
            designs,
            key=lambda design: (
                float(design["worst_smd"]), -len(design["presences"])),
        )

    selected_presences = selected_design["presences"].copy()
    matched = selected_design["background"].copy()
    worst_smd = float(selected_design["worst_smd"])
    retention = float(selected_design["retention"])
    selected_bins = int(selected_design["bins"])
    diagnostics_df = pd.DataFrame(
        candidate_diagnostics + list(selected_design["diagnostics"]))
    diagnostics_path = work_dir / OUTPUT_DIAGNOSTICS
    diagnostics_df.to_csv(diagnostics_path, index=False)
    if not valid_designs:
        raise RuntimeError(
            "No common-support design passed both predeclared gates. Best "
            f"attempt used {selected_bins} bins, retained "
            f"{len(selected_presences):,}/{len(presences):,} "
            f"({retention:.1%}) and had maximum |SMD|={worst_smd:.3f}. "
            f"Inspect {attempts_path.name} and {diagnostics_path.name}; no "
            "training layers were exported.")

    # p and b were concatenated in paired order. Pair identifiers make this
    # relationship auditable after independent Shapefile uploads.
    pair_ids = np.arange(1, len(selected_presences) + 1, dtype=int)
    selected_presences["match_pair_id"] = pair_ids
    matched["match_pair_id"] = pair_ids
    selected_presences["presence"] = 1
    selected_presences["variant"] = "recurrent_core_nondvi_accessmatch"
    selected_presences["time_window"] = "matched"
    selected_presences["pa_mode"] = "observed_accessmatch_subset"
    matched["presence"] = 0
    matched["variant"] = "recurrent_core_nondvi_accessmatch"
    matched["time_window"] = "matched"
    matched["pa_mode"] = "accessmatch_common_support"
    matched["pa_guard_rings"] = 0

    unmatched = presences.loc[
        ~presences.index.isin(selected_presences.index)].copy()
    unmatched["unmatched_reason"] = "outside_or_scarce_common_support_bin"
    unmatched_path = work_dir / OUTPUT_UNMATCHED
    pd.DataFrame(unmatched.drop(columns="geometry")).to_csv(
        unmatched_path, index=False)

    presence_4326 = selected_presences.to_crs(epsg=4326)
    background_4326 = matched.to_crs(epsg=4326)
    presence_gpkg_path = work_dir / OUTPUT_PRESENCE_GPKG
    background_gpkg_path = work_dir / OUTPUT_GPKG
    presence_4326.to_file(presence_gpkg_path, driver="GPKG")
    background_4326.to_file(background_gpkg_path, driver="GPKG")
    presence_zip_path, presence_crosswalk_path = write_gee_zip(
        presence_4326, work_dir, OUTPUT_PRESENCE_BASENAME)
    background_zip_path, background_crosswalk_path = write_gee_zip(
        background_4326, work_dir, OUTPUT_BASENAME)

    metadata = {
        "seed": SEED,
        "presence_input": str(presence_path),
        "candidate_pool_input": str(pool_path),
        "n_presence_input": int(len(presences)),
        "n_presence_matched": int(len(selected_presences)),
        "presence_retention_fraction": retention,
        "n_candidates_after_domain_and_effort_filter": int(len(candidates)),
        "n_matched_pseudo_absence": int(len(matched)),
        "analysis_esa_classes": ANALYSIS_ESA_CLASSES,
        "built_up_class_50_included": False,
        "open_water_class_80_included": True,
        "cropland_class_40_included": False,
        "bare_sparse_class_60_included": False,
        "presence_definition": {
            "minimum_platform_user_days": 3,
            "minimum_independent_users": 2,
            "minimum_distinct_dates": 2,
            "minimum_observation_span_days": 30,
        },
        "require_nonzero_effort": True,
        "candidate_pool_sampling": "primary effort-weighted candidate pool",
        "candidate_pool_implication": (
            "matched background inherits the broad spatial composition of "
            "the effort-weighted pool; SMD gate applies to specified marginals"),
        "exact_matching_variables": ["in_ordlo"],
        "continuous_matching_variables": [
            "log_effort", "log1p(dist_infra_m)"],
        "common_support_method": (
            "pooled-quantile coarsened exact matching within ORDLO, followed "
            "by nearest-neighbour allocation within each 2D bin"),
        "cem_bin_options_considered": CEM_BIN_OPTIONS,
        "selected_bins_per_covariate": selected_bins,
        "replacement": False,
        "maximum_absolute_smd": worst_smd,
        "smd_acceptance_limit": MAX_ABS_SMD,
        "minimum_presence_retention": MIN_PRESENCE_RETENTION,
        "robust_scaling_by_ordlo": selected_design["scaling"],
        "gee_presence_asset_name":
            f"{folders.ASSET_ROOT}/{ASSET_PREFIX}presences_recurrent_core_nondvi_accessmatch",
        "gee_background_asset_name":
            f"{folders.ASSET_ROOT}/{ASSET_PREFIX}pa_recurrent_core_nondvi_accessmatch_guard0",
    }
    metadata_path = work_dir / OUTPUT_METADATA
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print("\nCreated:")
    for path in [
        presence_gpkg_path, presence_zip_path, presence_crosswalk_path,
        background_gpkg_path, background_zip_path,
        background_crosswalk_path, diagnostics_path, attempts_path,
        unmatched_path, metadata_path,
    ]:
        print(f"  {path}")
    print(
        f"Selected CEM design: {selected_bins} bins per covariate; retained "
        f"{len(selected_presences):,}/{len(presences):,} presences "
        f"({retention:.1%}).")
    print(f"Maximum post-match |SMD|: {worst_smd:.3f}")
    print(f"Upload BOTH ZIP files in {UPLOAD_DIR} as Earth Engine table assets "
          "(asset name = ZIP name; IDs in the metadata JSON).")


if __name__ == "__main__":
    main()
